/**
 * Copies editor UI icons from the Game Engine repo into public/icons/editor/.
 * Upstream repo: https://github.com/Lunarsong/GameEngine
 * SVGs sync by default; PNG adds many large rasters — use only if you intentionally want them on the marketing site.
 *
 * Usage:
 *   node scripts/sync-editor-icons.mjs
 *   GAMEENGINE_EDITOR_ICONS=/absolute/path/to/Apps/Editor/Assets/Icons node scripts/sync-editor-icons.mjs
 *   GAMEENGINE_ROOT=/path/to/GameEngine node scripts/sync-editor-icons.mjs             # .../Apps/Editor/Assets/Icons
 *   node scripts/sync-editor-icons.mjs --png              # SVG + PNG (what the desktop editor ships for UI)

 */
import { cpSync, existsSync, mkdirSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const rootDir = join(__dirname, '..');
const destDir = join(rootDir, 'public', 'icons', 'editor');
const manifestPath = join(rootDir, 'src', 'lib', 'editor-icon-pngs.generated.ts');

/** Portable checkout locations; icons live at Apps/Editor/Assets/Icons under each. */
const DEFAULT_GAMEENGINE_ROOTS = [
	join(rootDir, '..', 'GameEngine'),
	join(rootDir, '../../GitHub/GameEngine'),
	join(rootDir, '../../../GitHub/GameEngine'),
	join(rootDir, '../GameEngine'),
];

/** Third-party icon downloads require an item-level license record before publication. */
function isPublishableIcon(name) {
	return !name.toLowerCase().includes('svgrepo-com');
}

function editorIconsUnderGameRoot(gameRoot) {
	return join(gameRoot, 'Apps', 'Editor', 'Assets', 'Icons');
}

function resolveSourceDir() {
	const env = process.env.GAMEENGINE_EDITOR_ICONS?.trim();
	if (env) {
		if (!existsSync(env)) {
			console.error(`GAMEENGINE_EDITOR_ICONS is set but path does not exist: ${env}`);
			process.exit(1);
		}
		return env;
	}

	const root = process.env.GAMEENGINE_ROOT?.trim();
	if (root) {
		const candidate = editorIconsUnderGameRoot(root);
		if (!existsSync(join(candidate, 'Lock.svg'))) {
			console.error(
				`GAMEENGINE_ROOT is set (${root}) but expected file missing:\n  ${join(candidate, 'Lock.svg')}`,
			);
			process.exit(1);
		}
		console.info(`Using editor icons from GAMEENGINE_ROOT: ${candidate}`);
		return candidate;
	}

	for (const gameRoot of DEFAULT_GAMEENGINE_ROOTS) {
		const candidate = editorIconsUnderGameRoot(gameRoot);
		if (existsSync(join(candidate, 'Lock.svg'))) {
			console.info(`Using editor icons source (no env set): ${candidate}`);
			return candidate;
		}
	}
	console.error(
		[
			'Could not find GameEngine Apps/Editor/Assets/Icons. Options:',
			'  GAMEENGINE_ROOT=/path/to/GameEngine                    (recommended)',
			'  GAMEENGINE_EDITOR_ICONS=/path/to/.../Assets/Icons',
			`Example: GAMEENGINE_ROOT=${DEFAULT_GAMEENGINE_ROOTS[0]} npm run sync:editor-icons`,
		].join('\n'),
	);
	process.exit(1);
}

/** Re-scan `destDir` so manifests stay aligned after SVG-only copies or manual edits. */
function writePngManifest() {
	const pngFiles = readdirSync(destDir)
		.filter((n) => n.toLowerCase().endsWith('.png') && isPublishableIcon(n))
		.sort((a, b) => a.localeCompare(b, 'en'));

	const header =
		'/**\n' +
		' * Editor UI PNG paths — generated by scripts/sync-editor-icons.mjs from public/icons/editor/*.png\n' +
		' * Do not edit by hand. Re-run after sync: npm run sync:editor-icons -- --png\n' +
		' */\n' +
		'export const EDITOR_ICON_PNG = {\n';

	const body =
		pngFiles.length === 0
			? ''
			: pngFiles
					.map((f) => {
						const stem = f.replace(/\.png$/i, '');
						const key = JSON.stringify(stem);
						const pathVal = JSON.stringify(`/icons/editor/${f}`);
						return `\t${key}: ${pathVal},`;
					})
					.join('\n');

	const footer = `\n} as const;\n\nexport type EditorIconPngKey = keyof typeof EDITOR_ICON_PNG;\n`;

	writeFileSync(manifestPath, `${header}${body}${footer}`, 'utf8');
	console.info(`sync-editor-icons: wrote ${pngFiles.length} PNG path(s) → src/lib/editor-icon-pngs.generated.ts`);
}

function sync() {
	const includePng = process.argv.includes('--png');
	const srcRoot = resolveSourceDir();
	mkdirSync(destDir, { recursive: true });

	let copied = 0;
	for (const name of readdirSync(srcRoot)) {
		const lower = name.toLowerCase();
		if (!(lower.endsWith('.svg') || (includePng && lower.endsWith('.png')))) continue;
		if (!isPublishableIcon(name)) continue;
		const from = join(srcRoot, name);
		const st = statSync(from);
		if (!st.isFile()) continue;
		if (name === '.DS_Store') continue;

		cpSync(from, join(destDir, name), { recursive: false });
		copied++;
	}

	console.info(
		includePng
			? `sync-editor-icons: copied ${copied} file(s) (SVG + PNG) → public/icons/editor/`
			: `sync-editor-icons: copied ${copied} SVG file(s) → public/icons/editor/ (--png adds editor PNG UI rasters too)`,
	);

	writePngManifest();
}

sync();
